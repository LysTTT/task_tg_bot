def keyboard(section: str = HOME) -> ReplyKeyboardMarkup:
    if section == HOME:
        rows = (("Новая задача", "Задачи"), ("Настройки", "Профиль"), (HELP,))
    else:
        rows = (*SECTIONS[section][0], (HOME, HELP), (CANCEL,))
    return ReplyKeyboardMarkup(
        keyboard=[[KeyboardButton(text=label) for label in row] for row in rows],
        resize_keyboard=True,
        is_persistent=True,
    )


def help_text() -> str:
    items = [
        *(f"«{label}» — {section[1]}" for label, section in SECTIONS.items()),
        *(f"«{label}» — {action[1]}" for label, action in ACTIONS.items()),
        f"«{HOME}» — возвращает к основным кнопкам.",
        f"«{CANCEL}» — закрывает запрос номера, даты или другого значения.",
        f"«{HELP}» — показывает эту справку.",
        "«Открыть №…» — показывает карточку задачи из списка.",
        "«Назад» и «Дальше» — листают страницы списка.",
    ]
    return "\n".join(items)
